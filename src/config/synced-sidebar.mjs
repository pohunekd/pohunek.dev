// The sidebar part of a product whose docs are synced at its pinned release. follow-release moves a pin and
// redeploys without a change to this site, so the sidebar follows the synced files instead of failing the build:
// a listed page the release no longer has is left out, and a page the list does not name is shown in a trailing
// group. Each case prints a warning in the build log. Plain .mjs so astro.config.mjs can import it.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** @typedef {NonNullable<import('@astrojs/starlight/types').StarlightUserConfig['sidebar']>[number]} SidebarItem */

const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));
// Starlight derives a slug from the file path; a route outside this shape could slug to another value.
const SLUG_SEGMENT = /^[a-z0-9][a-z0-9-]*$/;

/**
 * The slugs of the pages sync-docs wrote under `<contentDir>/<prefix>/`: each page is `<route>.md`, and `index.md`
 * is the prefix itself.
 * @param {string} contentDir
 * @param {string} prefix
 * @returns {string[]}
 */
export function syncedSlugs(contentDir, prefix) {
	const dir = join(contentDir, prefix);
	if (!existsSync(dir)) {
		throw new Error(`${dir} does not exist; run scripts/sync-docs.ts first`);
	}
	return readdirSync(dir, { recursive: true, encoding: 'utf8' })
		.filter((file) => file.endsWith('.md'))
		.map((file) => {
			const route = file.slice(0, -'.md'.length).split(sep).join('/');
			return route === 'index' ? prefix : `${prefix}/${route}`;
		})
		.sort();
}

/**
 * The hand-ordered sidebar without the slugs that `slugs` lacks (groups left empty are dropped), followed by a
 * group `label` holding the slugs it does not list. Links and autogenerated groups are kept as they are.
 * @param {readonly SidebarItem[]} sidebar
 * @param {readonly string[]} slugs
 * @param {string} label
 * @param {(message: string) => void} warn
 * @returns {SidebarItem[]}
 */
export function syncedSidebar(sidebar, slugs, label, warn) {
	const available = new Set(slugs);
	const listed = new Set();
	/** @param {readonly SidebarItem[]} items @returns {SidebarItem[]} */
	const keep = (items) =>
		items.flatMap((item) => {
			const slug = typeof item === 'string' ? item : 'slug' in item ? item.slug : undefined;
			if (slug !== undefined) {
				listed.add(slug);
				if (available.has(slug)) {
					return [item];
				}
				warn(`sidebar: ${slug} is not in the synced docs; left out`);
				return [];
			}
			if (typeof item !== 'string' && 'items' in item && Array.isArray(item.items)) {
				const kept = keep(item.items);
				return kept.length === 0 ? [] : [{ ...item, items: kept }];
			}
			return [item];
		});
	const kept = keep(sidebar);

	const unlisted = slugs.filter((slug) => {
		if (listed.has(slug)) {
			return false;
		}
		if (!slug.split('/').every((segment) => SLUG_SEGMENT.test(segment))) {
			warn(`sidebar: ${slug} is not listed and not a plain slug; left out`);
			return false;
		}
		warn(`sidebar: ${slug} is not listed; shown under "${label}"`);
		return true;
	});
	return unlisted.length === 0 ? kept : [...kept, { label, items: unlisted }];
}

/**
 * `syncedSidebar` for one product of docs-sync.config.json, read from the files its last sync wrote.
 * @param {readonly SidebarItem[]} sidebar
 * @param {string} product
 * @param {string} label
 * @returns {SidebarItem[]}
 */
export function productSidebar(sidebar, product, label) {
	const config = JSON.parse(readFileSync(join(REPO_ROOT, 'docs-sync.config.json'), 'utf8'));
	const source = config.sources.find((/** @type {{ product: string }} */ entry) => entry.product === product);
	if (source === undefined) {
		throw new Error(`docs-sync.config.json has no source for product "${product}"`);
	}
	return syncedSidebar(sidebar, syncedSlugs(join(REPO_ROOT, config.contentRoot), source.routePrefix), label, (message) =>
		console.warn(`${product} ${message}`),
	);
}
